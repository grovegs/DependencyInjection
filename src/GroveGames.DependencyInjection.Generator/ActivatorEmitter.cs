using System.Collections.Immutable;
using System.Text;

namespace GroveGames.DependencyInjection.Generator;

internal static class ActivatorEmitter
{
    private const string Namespace = "GroveGames.DependencyInjection.Generated";

    public static string? Emit(string providerName, ImmutableArray<TypeModel> registeredTypes, ImmutableArray<TypeModel> injectableTypes)
    {
        var types = Merge(registeredTypes, injectableTypes);

        if (types.Count == 0)
        {
            return null;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable disable");
        builder.AppendLine("#pragma warning disable CS0612, CS0618");
        builder.AppendLine();
        builder.Append("[assembly: global::").Append(Namespace).Append(".GeneratedActivatorsAttribute(typeof(global::").Append(Namespace).Append('.').Append(providerName).AppendLine("))]");
        builder.AppendLine();
        builder.Append("namespace ").AppendLine(Namespace);
        builder.AppendLine("{");
        builder.AppendLine("    [global::GroveGames.DependencyInjection.Scripting.Preserve]");
        builder.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"GroveGames.DependencyInjection.Generator\", \"1.0.0\")]");
        builder.Append("    internal sealed class ").Append(providerName).Append(" : global::").Append(Namespace).AppendLine(".IGeneratedActivatorProvider");
        builder.AppendLine("    {");
        builder.Append("        public void Register(global::").Append(Namespace).AppendLine(".GeneratedActivatorRegistry registry)");
        builder.AppendLine("        {");

        foreach (var type in types)
        {
            if (type.ConstructorParameterTypes is { } constructorParameterTypes)
            {
                builder.Append("            registry.AddConstructor(typeof(").Append(type.Name).Append("), ");
                AppendTypeArray(builder, constructorParameterTypes);
                builder.Append(", arguments => new ").Append(type.Name).Append('(');
                AppendArguments(builder, constructorParameterTypes);
                builder.AppendLine("));");
            }

            foreach (var method in type.InjectMethods)
            {
                builder.Append("            registry.AddInjectMethod(typeof(").Append(type.Name).Append("), ");
                AppendTypeArray(builder, method.ParameterTypes);
                builder.Append(", (instance, arguments) => ((").Append(type.Name).Append(")instance).").Append(method.Name).Append('(');
                AppendArguments(builder, method.ParameterTypes);
                builder.AppendLine("));");
            }
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static List<TypeModel> Merge(ImmutableArray<TypeModel> registeredTypes, ImmutableArray<TypeModel> injectableTypes)
    {
        var types = new Dictionary<string, TypeModel>(StringComparer.Ordinal);
        AddRange(types, registeredTypes);
        AddRange(types, injectableTypes);
        var result = new List<TypeModel>(types.Values);
        result.Sort(static (left, right) => string.CompareOrdinal(left.Name, right.Name));
        return result;
    }

    private static void AddRange(Dictionary<string, TypeModel> types, ImmutableArray<TypeModel> models)
    {
        foreach (var model in models)
        {
            if (!types.TryGetValue(model.Name, out var existing))
            {
                types.Add(model.Name, model);
                continue;
            }

            var constructor = existing.ConstructorParameterTypes ?? model.ConstructorParameterTypes;
            var injectMethods = existing.InjectMethods.Length > 0 ? existing.InjectMethods : model.InjectMethods;
            types[model.Name] = new TypeModel(model.Name, constructor, injectMethods);
        }
    }

    private static void AppendTypeArray(StringBuilder builder, EquatableArray<string> types)
    {
        if (types.Length == 0)
        {
            builder.Append("global::System.Type.EmptyTypes");
            return;
        }

        builder.Append("new global::System.Type[] { ");

        for (var i = 0; i < types.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append("typeof(").Append(types[i]).Append(')');
        }

        builder.Append(" }");
    }

    private static void AppendArguments(StringBuilder builder, EquatableArray<string> types)
    {
        for (var i = 0; i < types.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append("(").Append(types[i]).Append(")arguments[").Append(i).Append(']');
        }
    }
}
